'use strict';
const fs=require('node:fs'),crypto=require('node:crypto'),assert=require('node:assert/strict');
const path='sengoku/v2/approved-c-20261124-p2-88.json';
const m=JSON.parse(fs.readFileSync('docs/c-release/20261125-katsuyori-approved-v10.json','utf8'));
const bytes=fs.readFileSync(path),d=JSON.parse(bytes);
const sha=s=>crypto.createHash('sha256').update(s,'utf8').digest('hex');
const blob=crypto.createHash('sha1').update(Buffer.from('blob '+bytes.length+'\0')).update(bytes).digest('hex');
assert.equal(d.version,m.priorVersion);assert.equal(blob,m.priorBlob);
assert.deepEqual([d.people.length,d.histories.length,d.sites.length,d.relations.length,d.sites.filter(s=>s.publicPin).length],[88,1589,553,868,521]);
assert(!d.histories.some(x=>x.historyId===m.history.historyId));assert(!d.sites.some(x=>x.siteId===m.site.siteId));
assert.equal(sha(m.history.text),m.history.approval.sha256);
m.site.approval.sha256=sha(m.site.description);m.site.pinApproval={...m.site.approval};
d.histories.push(m.history);d.sites.push(m.site);d.relations.push(m.relation);d.municipalityAwards.push(m.graveAward);
const p=d.people.find(x=>x.personId===m.history.personId);assert(p);
assert.deepEqual([p.story.unlock.requiredHistoryCount,p.story.unlock.requiredPlaceHistoryCount],[24,15]);
p.story.unlock=m.unlock;
d.version=m.version;
d.notes.cRelease.v10={date:'2026-11-25',description:'Only approved Katsuyori site 4496 v3, history 4020 v2, direct ④608 and grave OR exception 38; preserve all others',priorRelease:m.priorVersion};
const core=require('../sengoku-v2-core.js'),codes=new Set(JSON.parse(fs.readFileSync('data/title-registry.json')).areas.map(x=>x.code));
const c=core.validate(d,codes,sha);
assert.deepEqual([c.people.size,c.histories.size,c.sites.size,d.relations.length,d.sites.filter(s=>s.publicPin).length],[88,1590,554,869,522]);
fs.writeFileSync(path,JSON.stringify(d,null,2)+'\n');
console.log('KATSUYORI_ONLY_RELEASE_VALIDATED');
