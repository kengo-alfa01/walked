'use strict';
const {test}=require('node:test'),assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.join(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const catalog=JSON.parse(fs.readFileSync(path.join(root,'sengoku/v2/approved-c-20261120-new9-80.json'),'utf8'));
const clean=require('../sengoku-card-cleanup.js');
const active=new Map(catalog.histories.map(h=>[h.historyId,h]));
const retired=catalog.retiredHistories.map(x=>x.history.historyId);
test('only current authorized histories are retained, all obsolete/unknown card IDs removed',()=>{
 const keep=catalog.histories[0].historyId,old=retired[0];
 const original={[keep]:{at:'2022-01-01',basis:'approved'},[old]:{at:'2020-01-01',basis:'retired'},'nonexistent-id':{at:'2018-01-01'}};
 const snapshot=JSON.stringify(original),value=clean.prune(original,{histories:active});
 assert.deepEqual(value.records,{[keep]:{at:'2022-01-01',basis:'approved'}});
 assert.deepEqual(value.removedIds,[old,'nonexistent-id']);
 assert.equal(JSON.stringify(original),snapshot,'pure cleanup must never mutate source before write');
 assert.deepEqual(clean.prune(value.records,{histories:active}),{records:value.records,removedIds:[]});
 assert.throws(()=>clean.prune(original,null),/確認が必要/);
});
test('all 74 character tiles and person selection depend on current-card ownership alone',()=>{
 const all=html.slice(html.indexOf('function renderSengoku(){'),html.indexOf('function toastSengokuCards(ids){'));
 assert.ok(all.includes('const owned=sengokuPeople.filter(p=>countOwned(p.id)>0)'));
 assert.ok(all.includes('if(!approved||countOwned(person.id)===0)return;'));
 assert.ok(!all.includes('ownedRetiredHistories'));
 assert.ok(!all.includes('旧公開版・取得済みカード'));
 assert.ok(!all.includes('旧カード保存'));
 assert.match(all,/count\.textContent=countOwned\(person\.id\)\+'\s*\/\s*'\+catalogCardCount\(person\.id\)\+' 枚'/);
});
test('the browser performs durable migration after signed catalog validation, before rendering',()=>{
 const inline=html.split('<script>').at(-1).split('</script>')[0];
 new vm.Script(inline,{filename:'index.html inline'});
 assert.ok(html.includes('sengoku-card-cleanup.js?v=c20261122-retired-purge'));
 assert.ok(html.includes('purgeRetiredSengokuCards(reviewed)'));
 assert.ok(html.includes('purgeObsoleteCheckpointCards(reviewed)'));
 const migrationStart=inline.indexOf('purgeRetiredSengokuCards(reviewed)');
 const validated=inline.indexOf('SengokuV2.validate(doc,');
 const rendered=inline.indexOf('renderSengoku();refreshSengokuPins();refreshSengokuAreaHighlights();',validated);
 assert.ok(validated>=0&&migrationStart>validated&&rendered>migrationStart);
 assert.ok(html.includes('writeStore(sengokuStoreKey,cleaned.records)'),'localStorage old IDs must physically be rewritten');
 assert.ok(html.includes('merged.cards=obsolete.records'),'backup restore must filter old IDs');
 assert.ok(html.includes('SengokuCardCleanup.prune(sengokuFound,sengokuV2Catalog).records'),'new backup must not contain old IDs');
 assert.ok(html.includes('SengokuCardCleanup.prune(previous.cards,sengokuV2Catalog).records'),'old pre-restore backup export must not resurrect IDs');
});
test('unchanged 419 public pins and approved active cards, retired manifest is only an audit source',()=>{
 assert.equal(catalog.sites.filter(s=>s.publicPin).length,419);
 assert.equal(catalog.people.length,74);
 assert.equal(catalog.histories.length,1251);
 assert.equal(retired.length,31);
 assert.ok(active.size>retired.length&&retired.every(id=>!active.has(id)),'retired IDs must be disjoint');
 assert.ok(!html.includes('const archive=ownedRetiredHistories'));
 assert.ok(!html.includes("archiveHead.textContent='旧公開版"));
 assert.ok(!html.includes("ownedRetiredHistories(p.id).length>0"));
});
