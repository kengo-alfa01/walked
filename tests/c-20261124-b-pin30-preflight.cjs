#!/usr/bin/env node
'use strict';
const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const json=p=>JSON.parse(read(p));
const sha=t=>crypto.createHash('sha256').update(t,'utf8').digest('hex');
const core=require('../sengoku-v2-core.js');
const m=json('docs/c-release/20261124-b-pin30-preflight.json');
const base=json('sengoku/v2/approved-c-20261120-new9-80.json');
const js=read('sengoku-v2-core.js');
const marker='const C20261124_30_PIN_META=Object.freeze(';
const start=js.indexOf(marker);
assert(start>=0,'C missing B-authoritative pin metadata');
const dataStart=start+marker.length;
const dataEnd=js.indexOf(');',dataStart);
assert(dataEnd>dataStart,'metadata block incomplete');
const approvedPins=JSON.parse(js.slice(dataStart,dataEnd));
const expected={green:4,yellow:18,red:8,existingPerson:19,newPerson:11};
assert.equal(m.batchId,'C-20261124-B-LOCATION-30');
assert.equal(m.releaseGate,'NOT_DEPLOYED');
assert.equal(m.sites.length,30);
assert.deepEqual(m.groupCounts,expected);
assert.equal(Object.keys(approvedPins).length,30);
assert.equal(m.affectedNewPeople.length,5);
const ids=new Set(),gates={green:0,yellow:0,red:0},personIds=new Set(base.people.map(x=>x.personId));
let oldCount=0,newCount=0;
for(const s of m.sites){
  assert(!ids.has(s.siteId),'duplicate site ID');ids.add(s.siteId);
  assert(!base.sites.some(x=>x.siteId===s.siteId),'site already in baseline');
  assert.equal(s.approval.user,'公開OK');
  assert.equal(s.approval.sourceMatch,'一致');
  assert.equal(s.approval.sourceId,s.siteId);
  assert(s.municipalityCodes.length>0&&s.municipalityCodes.every(x=>/^\d{5}$/.test(x)),'invalid municipality');
  assert.deepEqual(s.checks,{locationMatchesApproval:true,colorMatchesApproval:true,descriptionMatchesApproval:true,duplicateSiteId:false});
  assert.deepEqual(approvedPins[s.siteId],[s.approval.sheetRow,s.sourceSiteRow,s.point[0],s.point[1],s.accessStatus,'2026-11-24',s.approval.version]);
  assert(s.point[0]>120&&s.point[0]<155&&s.point[1]>20&&s.point[1]<47,'not a WGS84 Japan point');
  gates[s.accessStatus]++;
  if(personIds.has(s.approval.personId))oldCount++;else newCount++;
  const detail=core.pinDetails({name:s.name,publicPin:true,pinReview:{municipality:s.municipality,locationKind:'B承認済み参照地点',checkedAt:'2026-11-24',accessStatus:s.accessStatus,restriction:s.approvedPositionDisplayConditions,officialInfoUrl:null}});
  assert.equal(detail.noRouting,s.accessStatus==='red','red information pin routing mismatch');
}
assert.deepEqual(gates,{green:4,yellow:18,red:8});
assert.equal(oldCount,19);
assert.equal(newCount,11);
const knownCodes=json('data/title-registry.json').areas.map(x=>x.code);
const catalog=core.validate(base,knownCodes,sha);
assert.equal(catalog.people.size,74,'old people validation broken');
assert.equal(catalog.sites.size,436,'old site validation broken');
assert.equal(base.sites.filter(s=>s.publicPin).length,419,'old approved pins changed');
for(const p of m.affectedNewPeople)assert(js.includes(JSON.stringify(p.personId)),'new-person allowlist missing '+p.personId);
console.log('PASS: 30 B-approved pin metadata, 5 approved-person dependencies and unchanged 74-person/419-pin baseline');
console.log('NOT DEPLOYED: end-to-end candidate JSON / browser / Pages checks remain mandatory');
